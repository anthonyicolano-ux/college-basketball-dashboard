"""PRIVATE in-memory CBBD season record transformation. Never writes provider data.

The public demo files must only be generated by build_demo.py. This module
converts provider-shaped input into normalized rows for private QA only.
"""
import math
from metrics import safe_rate, per_game, effective_fg, true_shooting

SEASON = 2027


def get(record, dotted):
    node = record
    for key in dotted.split('.'):
        if not isinstance(node, dict) or key not in node:
            return None
        node = node[key]
    return node


def number(record, path):
    value = get(record, path)
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
        return None
    return value


def valid_identity(record, player=False):
    if not isinstance(record, dict) or record.get('season') != SEASON:
        raise ValueError('Missing or incorrect 2026-27 season')
    if not isinstance(record.get('team'), str) or not record['team'].strip():
        raise ValueError('Missing team')
    if player and (not isinstance(record.get('name'), str) or not record['name'].strip()):
        raise ValueError('Missing player name')


def team_row(record):
    valid_identity(record)
    games = number(record, 'games')
    if games is None or games < 0:
        raise ValueError('Invalid games')
    points = number(record, 'teamStats.points.total')
    opp_points = number(record, 'opponentStats.points.total')
    fgm = number(record, 'teamStats.fieldGoals.made')
    fga = number(record, 'teamStats.fieldGoals.attempted')
    threes = number(record, 'teamStats.threePointFieldGoals.made')
    fta = number(record, 'teamStats.freeThrows.attempted')
    team_rebounds = per_game(number(record, 'teamStats.rebounds.total'), games)
    opponent_rebounds = per_game(number(record, 'opponentStats.rebounds.total'), games)
    return {
        'team': record['team'], 'conference': record.get('conference'),
        'games': games, 'wins': number(record, 'wins'), 'losses': number(record, 'losses'),
        'ppg': per_game(points, games), 'oppPpg': per_game(opp_points, games),
        'offRating': number(record, 'teamStats.rating') or safe_rate(points, number(record, 'teamStats.possessions'), 100),
        'defRating': number(record, 'opponentStats.rating') or safe_rate(opp_points, number(record, 'opponentStats.possessions'), 100),
        'pace': number(record, 'pace'),
        'fgPct': safe_rate(fgm, fga, 100),
        'threePct': safe_rate(number(record, 'teamStats.threePointFieldGoals.made'), number(record, 'teamStats.threePointFieldGoals.attempted'), 100),
        'ftPct': safe_rate(number(record, 'teamStats.freeThrows.made'), fta, 100),
        'eFg': effective_fg(fgm, threes, fga),
        'tsPct': true_shooting(points, fga, fta),
        # Opponent fields are optional until their actual API paths are verified.
        # Never replace absent statistics with zero: rankings must exclude missing data.
        'threeMade': per_game(threes, games),
        'oppThreeMade': per_game(number(record, 'opponentStats.threePointFieldGoals.made'), games),
        'oppThreePct': safe_rate(number(record, 'opponentStats.threePointFieldGoals.made'),
                                 number(record, 'opponentStats.threePointFieldGoals.attempted'), 100),
        'oppFgPct': safe_rate(number(record, 'opponentStats.fieldGoals.made'),
                              number(record, 'opponentStats.fieldGoals.attempted'), 100),
        'oppRebounds': opponent_rebounds,
        'reboundingMargin': team_rebounds - opponent_rebounds if team_rebounds is not None and opponent_rebounds is not None else None,
        'oppAssists': per_game(number(record, 'opponentStats.assists'), games),
        'turnoversForced': per_game(number(record, 'opponentStats.turnovers.total'), games),
        'oppTurnovers': per_game(number(record, 'opponentStats.turnovers.total'), games),
        'rebounds': team_rebounds,
        'assists': per_game(number(record, 'teamStats.assists'), games),
        'turnovers': per_game(number(record, 'teamStats.turnovers.total'), games),
    }


def player_row(record):
    valid_identity(record, player=True)
    games = number(record, 'games')
    if games is None or games < 0:
        raise ValueError('Invalid games')
    return {
        'name': record['name'], 'team': record['team'], 'conference': record.get('conference'),
        'games': games, 'minutes': number(record, 'minutes'), 'points': number(record, 'points'),
        'rebounds': number(record, 'rebounds.total'), 'assists': number(record, 'assists'),
        'steals': number(record, 'steals'), 'blocks': number(record, 'blocks'),
        'turnovers': number(record, 'turnovers'),
        'fgMade': number(record, 'fieldGoals.made'), 'fgAttempted': number(record, 'fieldGoals.attempted'),
        'threeMade': number(record, 'threePointFieldGoals.made'), 'threeAttempted': number(record, 'threePointFieldGoals.attempted'),
        'ftMade': number(record, 'freeThrows.made'), 'ftAttempted': number(record, 'freeThrows.attempted'),
        'fgPct': safe_rate(number(record, 'fieldGoals.made'), number(record, 'fieldGoals.attempted'), 100),
        'threePct': safe_rate(number(record, 'threePointFieldGoals.made'), number(record, 'threePointFieldGoals.attempted'), 100),
        'ftPct': safe_rate(number(record, 'freeThrows.made'), number(record, 'freeThrows.attempted'), 100),
        'usage': number(record, 'usage'), 'offRating': number(record, 'offensiveRating'),
        'defRating': number(record, 'defensiveRating'),
        'trueShootingPct': number(record, 'trueShootingPct'),
        'winShares': number(record, 'winShares'), 'porpag': number(record, 'PORPAG'),
    }


def quality_summary(rows, fields):
    """Counts only; safe to log without exposing individual provider records."""
    return {'records': len(rows), 'non_null': {field: sum(row.get(field) is not None for row in rows) for field in fields}}


def private_validate(team_records, player_records):
    """Transform in memory; return summary only, never raw records."""
    teams = [team_row(r) for r in team_records]
    players = [player_row(r) for r in player_records]
    return {'season': SEASON,
            'teams': quality_summary(teams, ('ppg', 'oppPpg', 'offRating', 'defRating', 'pace', 'eFg', 'tsPct', 'threeMade', 'oppThreeMade', 'oppThreePct', 'oppFgPct', 'oppRebounds', 'oppAssists', 'turnoversForced')),
            'players': quality_summary(players, ('points', 'rebounds', 'assists', 'usage', 'offRating', 'defRating', 'trueShootingPct')),
            'publication': 'DISABLED: provider redistribution clearance required'}
